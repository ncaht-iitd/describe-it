// The real limit is 6 per minute; these tests generate more than that
process.env.GENERATE_PER_MINUTE = "1000";

const { test, before, after, beforeEach } = require("node:test");
const assert = require("node:assert/strict");
const mongoose = require("mongoose");
const request = require("supertest");
const { MongoMemoryServer } = require("mongodb-memory-server-core");

const describeClient = require("../lib/describeClient");
const auth = require("../lib/auth");
const app = require("../app");
const LibraryRecord = require("../models/LibraryRecord");
const GeneratedDescription = require("../models/GeneratedDescription");

let mongo;
let record;
let calls = [];
let currentUser = null;

before(async () => {
  mongo = await MongoMemoryServer.create();
  await mongoose.connect(mongo.getUri());
  // Fake the Describe service and the login check
  describeClient.describe = async (args) => {
    calls.push(args);
    return {
      alt_text: "A bar magnet with N and S poles.",
      long_description: `Generated by ${args.model}.`,
      model: { id: args.model, label: args.model.toUpperCase(), provider: "openai", name: args.model },
      prompt_version: "describe-v1",
      usage: { input_tokens: 10, output_tokens: 20 },
      seconds: 1.2,
    };
  };
  describeClient.listModels = async () => ({ models: [{ id: "gpt-4o", label: "GPT-4o" }], default_prompt: "describe-v1" });
  auth.verifyUser = async () => currentUser;
});

after(async () => {
  await mongoose.disconnect();
  await mongo.stop();
});

beforeEach(async () => {
  calls = [];
  currentUser = null;
  await LibraryRecord.deleteMany({});
  await GeneratedDescription.deleteMany({});
  record = await LibraryRecord.create({
    image_name: "class6_maths_ch5_primeTime_diagram_1.png", subject: "Mathematics", standard: "Class 6",
    chapter: { number: "5", name: " Prime Time " }, book: "NCERT", description: "Original hand-written description.",
  });
});

test("lists the models the Describe service offers", async () => {
  const res = await request(app).get("/api/describe/models").expect(200);
  assert.deepEqual(res.body.models.map((m) => m.id), ["gpt-4o"]);
});

test("generating sends the image and context, and stores the result in history", async () => {
  const res = await request(app).post(`/api/records/${record._id}/descriptions`).send({ model: "gpt-5.5" }).expect(201);
  assert.equal(res.body.data.long_description, "Generated by gpt-5.5.");
  assert.equal(calls[0].context.grade, "6");
  assert.equal(calls[0].context.chapter, "Prime Time");
  assert.ok(calls[0].base64.length > 100, "image bytes were sent");

  await request(app).post(`/api/records/${record._id}/descriptions`).send({ model: "gpt-4o" }).expect(201);
  const history = await request(app).get(`/api/records/${record._id}/descriptions`).expect(200);
  assert.deepEqual(history.body.data.map((d) => d.model.id), ["gpt-4o", "gpt-5.5"], "newest first");

  const unchanged = await LibraryRecord.findById(record._id);
  assert.equal(unchanged.description, "Original hand-written description.", "generating never changes the library");
});

test("generating needs a model and an existing diagram", async () => {
  await request(app).post(`/api/records/${record._id}/descriptions`).send({}).expect(400);
  await request(app).post(`/api/records/${new mongoose.Types.ObjectId()}/descriptions`).send({ model: "gpt-4o" }).expect(404);
  await request(app).post("/api/records/not-an-id/descriptions").send({ model: "gpt-4o" }).expect(404);
});

test("service errors are passed on with a readable message", async () => {
  const original = describeClient.describe;
  describeClient.describe = async () => { throw new describeClient.ServiceError("GPT-4o could not answer: rate limited", 502); };
  try {
    const res = await request(app).post(`/api/records/${record._id}/descriptions`).send({ model: "gpt-4o" }).expect(502);
    assert.match(res.body.error, /rate limited/);
  } finally {
    describeClient.describe = original;
  }
});

test("only admins can save a description to the library", async () => {
  const gen = (await request(app).post(`/api/records/${record._id}/descriptions`).send({ model: "gpt-4o" })).body.data;
  const url = `/api/records/${record._id}/descriptions/${gen._id}/save`;

  await request(app).post(url).expect(401);
  currentUser = { id: "u1", name: "Reader", isAdmin: false };
  await request(app).post(url).expect(403);
  assert.equal((await LibraryRecord.findById(record._id)).description, "Original hand-written description.");
});

test("saving replaces the library text but keeps the old description in history", async () => {
  const gen = (await request(app).post(`/api/records/${record._id}/descriptions`).send({ model: "gpt-4o" })).body.data;
  currentUser = { id: "a1", name: "Admin", email: "admin@example.org", isAdmin: true };
  await request(app).post(`/api/records/${record._id}/descriptions/${gen._id}/save`).expect(200);

  const saved = await LibraryRecord.findById(record._id);
  assert.equal(saved.description, "Generated by gpt-4o.");
  assert.equal(saved.alt_text, "A bar magnet with N and S poles.");
  assert.equal(saved.description_meta.saved_by, "admin@example.org");

  const history = (await request(app).get(`/api/records/${record._id}/descriptions`)).body.data;
  const kept = history.find((d) => d.source === "library");
  assert.equal(kept.long_description, "Original hand-written description.");
  assert.ok(history.find((d) => d._id === gen._id).saved_to_library_at);

  // Saving again does not duplicate the kept copy
  await request(app).post(`/api/records/${record._id}/descriptions/${gen._id}/save`).expect(200);
  const again = (await request(app).get(`/api/records/${record._id}/descriptions`)).body.data;
  assert.equal(again.filter((d) => d.source === "library").length, 1);
});

test("/api/me says whether the visitor is an admin", async () => {
  assert.equal((await request(app).get("/api/me")).body.user, null);
  currentUser = { name: "Admin", isAdmin: true };
  assert.deepEqual((await request(app).get("/api/me")).body.user, { name: "Admin", isAdmin: true });
});
